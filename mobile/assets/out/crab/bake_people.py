#!/usr/bin/env python3
"""Bake the traced cheer-model parts into a module of normalised polygons.

Feet on the origin, figure 200 units tall, x centred on the trousers. Nothing
here is redrawn — these are the contours trace_person_full.py pulled out of the
photo, only translated and scaled.
"""
import json

parts = json.load(open('ref/people/cheer_parts.json'))
ORDER = ['leg_back', 'trousers', 'black1', 'jacket', 'lapel', 'black2',
         'face', 'hatband', 'fist1', 'fist2']
NAME = {'leg_back': 'LEG_BACK', 'trousers': 'TROUSERS', 'black1': 'SHIRT',
        'jacket': 'JACKET', 'lapel': 'LAPEL', 'black2': 'HAT',
        'face': 'FACE', 'hatband': 'BAND',
        'fist1': 'FIST_L', 'fist2': 'FIST_R'}
by = {p['name']: p for p in parts}

xs = [x for p in parts for x, y in p['pts']]
ys = [y for p in parts for x, y in p['pts']]
H = max(ys) - min(ys)
k = 200.0 / H
tx, ty = by['trousers']['bbox'][0] + by['trousers']['bbox'][2] / 2, max(ys)

out = ['#!/usr/bin/env python3',
       '"""AUTO-GENERATED by bake_people.py — traced contours, do not hand-edit.',
       '',
       f'Source: ref/people/cheer.jpg, upscaled 5x. Figure is {H}px tall in the',
       f'photo; every point below is (p - trousers_centre) * {k:.5f} so the',
       'figure stands 200 units tall with its feet on the origin.',
       '"""',
       '']
for nm in ORDER:
    if nm not in by:
        continue
    pts = [((x - tx) * k, (y - ty) * k) for x, y in by[nm]['pts']]
    b = by[nm]['bbox']
    out.append(f'# {nm}: {b[2]}x{b[3]} in the photo, {len(pts)} vertices')
    out.append(f'{NAME[nm]} = [' + ', '.join(f'({x:.1f}, {y:.1f})'
                                             for x, y in pts) + ']')
# face marks, traced as ink components inside the face box rather than placed
# by eye: two eye dots and the slanted mouth
EYES_PX = [(298, 259, 7.5), (342, 251, 8.0)]
MOUTH_PX = [(383, 265), (322, 291)]
out.append('')
out.append('# eye dots: (cx, cy, r), traced from the ink inside the face box')
out.append('EYES = [' + ', '.join(
    f'({(x - tx) * k:.1f}, {(y - ty) * k:.1f}, {r * k:.1f})'
    for x, y, r in EYES_PX) + ']')
out.append('# mouth: the slanted stroke, traced')
out.append('MOUTH = [' + ', '.join(f'({(x - tx) * k:.1f}, {(y - ty) * k:.1f})'
                                   for x, y in MOUTH_PX) + ']')
out.append('MOUTH_W = 4.2')
out.append("ORDER = ['LEG_BACK', 'TROUSERS', 'SHIRT', 'JACKET', 'LAPEL', "
           "'HAT', 'FACE', 'BAND', 'FIST_L', 'FIST_R']")

open('people_parts.py', 'w').write('\n'.join(out) + '\n')
print('\n'.join(out[:8]))
for nm in ORDER:
    if nm in by:
        b = by[nm]['bbox']
        print(f'  {NAME[nm]:9s} {b[2]*k:6.1f} x {b[3]*k:6.1f} units, '
              f'{len(by[nm]["pts"])} verts')
